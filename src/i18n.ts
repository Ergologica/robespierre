export type Lang = 'it' | 'en'
let current: Lang = 'it'
export let L: Dict = it

export function getLang(): Lang { return current }
export function setLang(lang: Lang): void {
  current = lang
  L = lang === 'it' ? it : en
  setNumberLocale(lang)
  setRelativeWords(lang === 'it'
    ? { now: 'ora', s: 's fa', min: 'min fa', h: 'ore fa', d: 'giorni fa' }
    : { now: 'now', s: 's ago', min: 'min ago', h: 'h ago', d: 'days ago' })
  try { localStorage.setItem('robespierre.lang', lang) } catch { /* best effort */ }
  if (typeof document !== 'undefined') document.documentElement.lang = lang
}
export function initLang(): void {
  let saved: string | null = null
  try { saved = localStorage.getItem('robespierre.lang') } catch { /* ignore */ }
  setLang(saved === 'en' ? 'en' : 'it')
}
